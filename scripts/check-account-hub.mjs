import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (p) => readFileSync(p,"utf8");
const hub = read("app/merchant/account/page.tsx");
const oldLogin = read("app/merchant/login/page.tsx");
const oldRegister = read("app/merchant/register/page.tsx");
const login = read("components/merchant/merchant-login-panel.tsx");
const register = read("components/merchant/merchant-register-panel.tsx");
const header = read("app/layout.tsx");
const homepage = read("app/page.tsx");
const admin = read("app/admin/login/page.tsx");
assert.ok(hub.includes('aria-label="商戶帳戶"'), "Unified account tabs need accessible navigation");
assert.ok(hub.includes('mode === "register" ? <MerchantRegisterPanel /> : <MerchantLoginPanel />'), "Same hub must render one form at a time");
assert.ok(hub.includes('aria-current={mode === "login"') && hub.includes('aria-current={mode === "register"'), "Active tab must be distinguishable to screen readers");
assert.ok(hub.includes('href="/admin/login"'), "Admin sign in must remain discoverable");
assert.ok(oldLogin.includes('export { default, metadata } from "../account/page"'), "Legacy login must render same hub without stripping email confirmation code or hash");
assert.ok(oldRegister.includes('redirect("/merchant/account?mode=register")'), "Legacy registration URL and old campaigns must keep working");
assert.ok(login.includes('signInWithPassword('), "Email login must remain enabled");
assert.ok(login.includes('signInWithOAuth('), "Provider authentication must remain supported");
assert.ok(login.includes('href="/merchant/forgot-password"'), "Password recovery link required");
assert.ok(login.includes('autoComplete="current-password"'), "Password autofill must remain supported");
assert.ok(login.includes('showPassword ? "text" : "password"'), "Explicit user password visibility toggle needed");
assert.ok(register.includes('supabase.auth.signUp('), "Registration must still create an actual Auth account");
assert.ok(register.includes('CURRENT_MERCHANT_TERMS_VERSION'), "Legal acceptance versioning must remain");
assert.ok(register.includes('CURRENT_PRIVACY_VERSION'), "Privacy consent versioning must remain");
assert.ok(register.includes('emailRedirectTo: `${window.location.origin}/merchant/login`'), "Supabase email confirm must use existing allowed redirect URL, then legacy redirect to new hub");
assert.ok(register.includes('data.user.identities?.length === 0'), "Supabase obfuscated duplicate identities must not claim success");
assert.ok(register.includes('account_type: "merchant"'), "Merchant type metadata must stay unchanged");
assert.ok(header.includes('href="/admin/login"'), "Homepage header or footer must expose Admin sign in");
assert.ok(header.includes('href="/merchant/account?mode=login"'), "Merchant sign-in entry must use common hub");
assert.ok(header.includes('href="/merchant/account?mode=register"'), "Merchant free registration entry must use common hub");
assert.ok(homepage.includes('href="/merchant/account?mode=login"'), "Homepage Merchant CTA must use unified account");
assert.ok(homepage.includes('href="/merchant/account?mode=register"'), "Homepage registration CTA must use unified account");
assert.ok(!admin.includes("Password only"), "Never display authentication configuration internals to public");
assert.ok(!admin.includes("毋須 QR Code"), "Do not publicly announce security internals");
assert.ok(admin.includes('rpc("is_platform_admin")'), "Only authorized platform admins can enter admin");
assert.ok(admin.includes('signOut()'), "Non-admin sessions must be rejected");
assert.ok(!homepage.includes("Admin 設定精選活動後"), "Public empty state cannot reveal editorial internals");
assert.ok(hub.includes('robots: { index: false, follow: false }'), "Credential entry must not be indexed");
console.log("[account-hub] PASS — unified login/register, legacy redirects, privacy, admin discovery and auth isolation");
